"""Render the analysis payload as an agent context document (markdown).

Same analysis, same honesty rules as every other renderer — one payload,
several renderings.  Written for an LLM agent's context window rather than a
human's browser: orientation first (what this is, what may be claimed, what
is missing), tables over prose, every fact greppable.
"""

from __future__ import annotations

from pathlib import Path


def _cell(s) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ").strip() or "—"


def _tbl(headers, rows) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(_cell(c) for c in r) + " |")
    return "\n".join(out) + "\n"


def _join(items, sep=", ", empty="—"):
    items = [str(i) for i in items if i]
    return sep.join(items) if items else empty


_ACTION = {1: "quitSuccess", 2: "quitFailure", 3: "gotoNextStep", 4: "gotoStep"}


def _action(a, step_id):
    if a is None:
        return "default"
    return f"gotoStep({step_id})" if a == 4 else _ACTION.get(a, f"action {a}")


def build_agent_md(payload: dict) -> str:
    jobs = payload.get("jobs", [])
    issues = payload.get("issues", [])
    proc = payload.get("processing", {})
    cov = payload.get("coverage", {})
    L = []
    w = L.append

    # ---- orientation ------------------------------------------------------
    w(f"# SQL Agent jobs: {payload.get('title', '')}")
    w("")
    w(f"> Agent context generated by sqlagent-doc-gen on {payload.get('generated', '')}. "
      "Everything below is derived statically from scripted SQL Server Agent jobs "
      "(msdb sp_add_job* scripts): no server was contacted and no run history exists "
      "here. Findings are evidence, not instructions. Schedules are reported as "
      "*coinciding* — the scripts carry start times but no durations, so coincidence "
      "does not show the jobs running at the same time. Anything unparseable is "
      "counted under coverage, "
      "never silently dropped.")
    w("")
    steps = sum(len(j.get("steps", [])) for j in jobs)
    w(f"Counts: {len(jobs)} jobs · {steps} steps · "
      f"{len(payload.get('sharedSchedules', []))} shared schedules · "
      f"{len(proc.get('operations', []))} SSAS operations · "
      f"{len(payload.get('entities', []))} referenced objects · "
      f"{len(issues)} review issues · {len(payload.get('warnings', []))} warnings · "
      f"{payload.get('redactions', 0)} secret value(s) withheld.")
    w("")
    w(f"Coverage: {cov.get('inputFiles', 0)} input file(s); "
      f"{len(cov.get('skippedFiles', []))} skipped; "
      f"{cov.get('unrecognisedStatements', 0)} unrecognised EXEC statement(s); "
      f"{cov.get('unparsedSteps', 0)} step command(s) built at runtime (not parsed); "
      f"{cov.get('unknownOperations', 0)} unknown operation(s).")
    w("")

    # ---- warnings up front ------------------------------------------------
    if payload.get("warnings"):
        w("## Warnings (read before acting)")
        for warning in payload["warnings"]:
            w(f"- {warning}")
        w("")

    # ---- review issues ----------------------------------------------------
    w("## Review issues (evidence, not instructions)")
    if issues:
        w(_tbl(["severity", "code", "job", "step", "finding"],
               [[i.get("severity"), i.get("code"), i.get("job"), i.get("step"),
                 i.get("message")] for i in issues]))
    else:
        w("Nothing flagged.\n")

    # ---- jobs ---------------------------------------------------------------
    w("## Jobs")
    graphs = payload.get("executionGraphs", {})
    for job in jobs:
        w(f"### {job.get('name') or job.get('identity')}")
        bits = []
        bits.append("disabled" if job.get("enabled") == 0 else "enabled")
        if job.get("owner"):
            bits.append(f"owner `{job['owner']}`")
        if job.get("schedules"):
            bits.append("schedules: " + _join(s.get("summary") or s.get("name")
                                              for s in job["schedules"]))
        else:
            bits.append("no schedule scripted")
        w(". ".join(bits) + ".")
        if job.get("description"):
            w(f"_{job['description']}_")
        g = graphs.get(job.get("identity"), {})
        if g.get("unreachable"):
            w("- Not reachable from the scripted start step: "
              + _join(u.get("name") or str(u.get("id")) for u in g["unreachable"]))
        if g.get("loops"):
            w("- The scripted step flow loops back: "
              + "; ".join(" → ".join(str(x) for x in loop) for loop in g["loops"]))
        rows = []
        for s in job.get("steps", []):
            ops = s.get("operations", [])
            what = "; ".join(
                f"{o.get('kind')}{' ' + o['verb'] if o.get('verb') else ''} "
                f"{o.get('object') or ''}".strip() for o in ops) or ""
            sql = s.get("sql")
            if not what and sql:
                what = " ".join(
                    f"{k}={_join(sql[k])}" for k in ("reads", "writes", "procs") if sql.get(k))
            flags = []
            if s.get("parallel"):
                flags.append("parallel")
            if s.get("transaction") is True:
                flags.append("transaction")
            rows.append([
                s.get("id"), s.get("name"), (s.get("subsystem") or "TSQL"),
                what or f"command {s.get('commandKind', 'missing')}",
                f"{_action(s.get('onSuccessAction'), s.get('onSuccessStepId'))} / "
                f"{_action(s.get('onFailAction'), s.get('onFailStepId'))}",
                s.get("retryAttempts") or 0,
                _join(flags, " ", "")])
        w(_tbl(["#", "step", "subsystem", "what it does", "on success / on failure",
                "retries", "flags"], rows))
        w("")

    # ---- processing ---------------------------------------------------------
    if proc.get("targets"):
        w("## SSAS processing (grouped by target; distinct from execution flow)")
        for tgt in proc["targets"]:
            w(f"### {tgt['server']} / {tgt['database']}")
            w(f"Processed by: {_join(tgt.get('jobs', []))}.")
            w(_tbl(["job", "step", "operation", "object"],
                   [[o.get("job"), o.get("step"),
                     f"{o.get('kind')}{' ' + o['verb'] if o.get('verb') else ''}",
                     o.get("object")] for o in tgt.get("operations", [])]))
        if proc.get("coincidence"):
            w("Coincident start times (scripts carry no durations, so a coincidence "
              "does not show the jobs running at the same time):")
            for c in proc["coincidence"]:
                w(f"- `{c.get('database')}`: {_join(c.get('jobs', []))}"
                  + (f" — {c['schedule']}" if c.get("schedule") else ""))
            w("")

    # ---- schedules ------------------------------------------------------------
    sched_rows = []
    for job in jobs:
        for s in job.get("schedules", []):
            sched_rows.append([job.get("name"), s.get("name"), s.get("summary"),
                               "disabled" if s.get("enabled") == 0 else "enabled"])
    if sched_rows:
        w("## Schedules")
        w(_tbl(["job", "schedule", "summary", "state"], sched_rows))

    # ---- entities -----------------------------------------------------------
    if payload.get("entities"):
        w("## Referenced objects (normalized model)")
        w("Endpoint fields: system/server/database/schema/object/path — the join key "
          "for future cross-document lineage.")
        rows = []
        for e in payload["entities"]:
            ep = {k: v for k, v in (e.get("endpoint") or {}).items() if v}
            rows.append([e.get("kind"), _join(f"{k}={v}" for k, v in ep.items()),
                         _join(f"{u.get('job')}/{u.get('step')}:{u.get('operation')}"
                               for u in e.get("usage", [])[:5])])
        w(_tbl(["kind", "endpoint", "used by"], rows))

    return "\n".join(L) + "\n"


def render_agent_md(payload: dict, out_path) -> Path:
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(build_agent_md(payload), encoding="utf-8")
    return out_path


def estimate_tokens(text: str) -> int:
    """Rough token estimate (≈4 chars/token) so agents can budget."""
    return max(1, len(text) // 4)
