"""SQL Agent lineage through the real adapters (rel-rules/2): what the engines emit, not hand-built bindings.

Every input is synthetic and names no real system.
"""
import json
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from bidoc_contracts import locate_manifest  # noqa: E402
from bidoc_engines.generate import GenerateRequest, generate  # noqa: E402
from bidoc_relationships import Document, detect  # noqa: E402

NS = 'xmlns="http://schemas.microsoft.com/analysisservices/2003/engine"'
JOB = """EXEC msdb.dbo.sp_add_job @job_name = N'Seeded {name}', @owner_login_name = N'etl'
EXEC msdb.dbo.sp_add_jobstep @job_name = N'Seeded {name}', @step_id = 1, @step_name = N'{name}',
    @subsystem = N'ANALYSISCOMMAND', @server = N'{server}', @command = N'{command}'
"""
TMSL_REFRESH = '{"refresh": {"type": "full", "objects": [{"database": "SeededModel"}]}}'


class _Engines(unittest.TestCase):
    """Helpers: documents generated by the real engines, as rel-rules/2 sees them."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        self.n = 0

    def document(self, engine, source, kind) -> Document:
        r = generate(GenerateRequest(engine=engine, source_path=str(source), source_kind=kind,
                                     output_dir=str(self.tmp / "out"), environment="Production"))
        self.assertEqual(r.status, "completed", r.errors)
        m = json.loads(locate_manifest(Path(r.artifact_path).read_bytes()).body)
        return Document(m["document_id"], m["revision_id"], m["document_type"],
                        m["publication"]["environment_key"], tuple(m["objects"]))

    def job(self, name, command, server="SEEDED-SSAS-01\\TABULAR") -> Document:
        self.n += 1
        script = self.tmp / f"job{self.n}" / f"{name}.sql"
        script.parent.mkdir(parents=True)
        script.write_text(JOB.format(name=name, server=server, command=command), encoding="utf-8")
        return self.document("sql_agent", script, "agent_script")

    def live_report(self, database, server="SEEDED-SSAS-01\\TABULAR") -> Document:
        self.n += 1
        report = self.tmp / f"thin{self.n}" / "Seeded.Report"
        (report / "definition" / "pages").mkdir(parents=True)
        (report / "definition.pbir").write_text(json.dumps({"version": "4.0", "datasetReference": {"byConnection": {
            "connectionString": f"Data Source={server};Initial Catalog={database}"}}}), encoding="utf-8")
        (report / "definition" / "report.json").write_text("{}", encoding="utf-8")
        (report / "definition" / "pages" / "pages.json").write_text('{"pageOrder": []}', encoding="utf-8")
        return self.document("power_bi", report, "pbir")

    def sql_model(self, server, database, schema, table) -> Document:
        self.n += 1
        model = {"model": {"name": "Seeded SQL model", "tables": [{
            "name": table, "lineageTag": f"4d4e5f60-0000-4000-8000-{self.n:012d}", "columns": [{"name": "Amount"}],
            "partitions": [{"name": table, "source": {"type": "m", "expression":
                            f'let Source = Sql.Database("{server}", "{database}"),\n'
                            f'    T = Source{{[Schema="{schema}",Item="{table}"]}}[Data]\nin\n    T'}}]}]}}
        folder = self.tmp / f"pbi{self.n}"
        folder.mkdir()
        (folder / "model.bim").write_text(json.dumps(model), encoding="utf-8")
        return self.document("power_bi", folder / "model.bim", "bim")

    @staticmethod
    def found(docs):
        return [(r["kind"], r["confidence"]) for r in detect(docs)]


class RealAdapterLineage(_Engines):
    # -- review: non-processing model commands never relate ---------------------------------------------------------

    def test_synchronize_relates_to_neither_model(self):
        sync = (f"<Synchronize {NS}><Object><DatabaseID>SeededModel</DatabaseID></Object>"
                f"<Source><DatabaseID>SeededStaging</DatabaseID></Source></Synchronize>")
        job = self.job("Sync", sync)
        ops = {b["operation"] for o in job.objects for b in o["bindings"]}
        self.assertEqual(ops, {"execute", "read"})            # the adapter does emit both; the rules must ignore both
        self.assertEqual(self.found([job, self.live_report("SeededStaging")]), [])
        self.assertEqual(self.found([job, self.live_report("SeededModel")]), [])

    def test_processing_still_relates_and_its_relational_read_is_a_reader(self):
        process_add = (f"<Batch {NS}><Process><Type>ProcessAdd</Type><Object><DatabaseID>SeededModel</DatabaseID>"
                       f"<CubeID>Sales</CubeID></Object><Bindings><Binding><DataSourceID>Staging</DataSourceID>"
                       f"</Binding></Bindings></Process></Batch>")
        job = self.job("Process", process_add)
        self.assertEqual(self.found([job, self.live_report("SeededModel")]), [("produces", "possible")])   # XMLA ID
        self.assertEqual(self.found([job, self.sql_model("sql1.corp.local", "DW", "dbo", "Staging")]),
                         [("reads", "possible")])

    # -- review: ports --------------------------------------------------------------------------------------------

    def test_tmsl_refresh_and_live_report_exact_only_when_ports_agree(self):
        job = self.job("Refresh", TMSL_REFRESH)
        self.assertEqual(self.found([job, self.live_report("SeededModel")]), [("produces", "exact_static")])
        found = detect([job, self.live_report("SeededModel", server="SEEDED-SSAS-01\\TABULAR,2383")])
        self.assertEqual([(r["kind"], r["confidence"]) for r in found], [("produces", "possible")])
        self.assertIn("port known on one side only", found[0]["evidence"]["notes"])
        with_port = self.job("Refresh with port", TMSL_REFRESH, server="SEEDED-SSAS-01\\TABULAR,2383")
        self.assertEqual(self.found([with_port, self.live_report("SeededModel", server="SEEDED-SSAS-01\\TABULAR,2383")]),
                         [("produces", "exact_static")])
        self.assertEqual(self.found([with_port, self.live_report("SeededModel", server="SEEDED-SSAS-01\\TABULAR,2384")]),
                         [])


class CrossDatabaseLoads(_Engines):
    def tsql_job(self, command, database="master") -> Document:
        self.n += 1
        script = self.tmp / f"tsql{self.n}" / "load.sql"
        script.parent.mkdir(parents=True)
        script.write_text("EXEC msdb.dbo.sp_add_job @job_name = N'Seeded Load'\n"
                          "EXEC msdb.dbo.sp_add_jobstep @job_name = N'Seeded Load', @step_name = N'load',\n"
                          f"    @database_name = N'{database}', @command = N'{command}'\n", encoding="utf-8")
        return self.document("sql_agent", script, "agent_script")

    def test_a_three_part_write_links_to_the_report_reading_that_table(self):
        job = self.tsql_job("INSERT INTO Sales.dbo.FactSales SELECT * FROM dbo.Staged")
        writes = [b for o in job.objects for b in o["bindings"] if b["operation"] == "write"]
        self.assertEqual([(b["endpoint"]["database"], b["endpoint"]["schema"], b["endpoint"]["object"]) for b in writes],
                         [("Sales", "dbo", "FactSales")])
        found = detect([job, self.sql_model("sql1.corp.local", "Sales", "dbo", "FactSales")])
        self.assertEqual([(r["kind"], r["confidence"]) for r in found], [("produces", "possible")])
        self.assertIn("server known on one side only", found[0]["evidence"]["notes"])
        self.assertEqual(self.found([job, self.sql_model("sql1.corp.local", "master", "dbo", "FactSales")]), [])

    def test_a_linked_server_name_is_context_not_the_server(self):
        job = self.tsql_job("INSERT INTO REMOTE.Sales.dbo.FactSales SELECT 1")
        write = next(b for o in job.objects for b in o["bindings"] if b["operation"] == "write")
        self.assertEqual((write["endpoint"]["server"], write["endpoint"]["database"]), (None, "Sales"))
        self.assertEqual(write["invocation_context"]["linked_server"], "REMOTE")
        self.assertEqual(self.found([job, self.sql_model("sql1.corp.local", "Sales", "dbo", "FactSales")]),
                         [("produces", "possible")])


